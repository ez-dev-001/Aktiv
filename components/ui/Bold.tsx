/**
 * `**жирный**` внутри строки.
 *
 * ── Почему не markdown-парсер ──
 * Из всей разметки в редактируемых текстах нужно ровно одно: выделить
 * внутри абзаца одну-две фразы. Ради этого тянуть `remark` с его
 * плагинами и санитайзером — 40 КБ в бандл и новый класс ошибок
 * (вложенные списки, ссылки, HTML-вставки), которых в поле
 * «Вступний текст» быть не должно вообще.
 *
 * Здесь split по регулярке и чередование частей: чётные индексы —
 * обычный текст, нечётные — то, что было между звёздочками. Ничего
 * другого разметка не умеет, и это её достоинство: редактор не может
 * случайно сломать вёрстку страницы, вставив в поле таблицу.
 *
 * ── Откуда взялся onDark ──
 * Раньше эта функция была скопирована в трёх файлах, и копии
 * разошлись именно по цвету: в Sections выделение было `text-white`
 * (для тёмных секций), в TrustedBy — `text-ink` (для бумаги). Правка
 * в одном месте не доезжала до двух других. Теперь фон — параметр, а
 * код один.
 */
export function Bold({ text, onDark = false }: { text: string; onDark?: boolean }) {
  return (
    <>
      {text.split(/\*\*(.+?)\*\*/g).map((part, i) =>
        i % 2 === 1 ? (
          <strong key={i} className={onDark ? 'font-medium text-white' : 'font-medium text-ink'}>
            {part}
          </strong>
        ) : (
          part
        ),
      )}
    </>
  )
}
