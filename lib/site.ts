/**
 * Адрес сайта и признак «это настоящий сайт, а не тестовый».
 *
 * Один источник для metadataBase, карты сайта и robots.txt: если
 * адрес записан в трёх местах, при переезде на другой домен одно из
 * них обязательно забудут, и Google получит карту со ссылками на
 * старый.
 */
export const SITE_URL = 'https://aktiv-alb.com'

/**
 * Можно ли этот деплой индексировать.
 *
 * ── Зачем ──
 * Netlify собирает сайт не только на боевом домене: у каждого деплоя
 * есть адрес вида *.netlify.app, у каждой ветки и pull request — свой
 * предпросмотр. Если их не закрыть, Google найдёт копии сайта и увидит
 * дубли: три-четыре одинаковых сайта на разных адресах, и неизвестно,
 * какой из них главный. Страдают позиции настоящего.
 *
 * Раньше в инструкции по тестовому деплою было написано «добавьте
 * robots: noindex и не забудьте убрать перед запуском». Забыть убрать —
 * значит выкатить настоящий сайт, закрытый от поиска целиком, и узнать
 * об этом через месяц по пустой Search Console. Здесь решение
 * принимается само, по переменным, которые Netlify выставляет в сборке:
 *
 *   CONTEXT — production, deploy-preview или branch-deploy;
 *   URL     — главный адрес сайта: netlify.app, пока домен не привязан,
 *             и aktiv-alb.com после привязки.
 *
 * Индексировать можно только production-сборку на боевом домене.
 * Локально (переменных нет) — тоже можно: robots.txt на localhost
 * никто не читает, а проверять его содержимое удобнее в открытом виде.
 */
export function isIndexable(): boolean {
  const context = process.env.CONTEXT
  const url = process.env.URL
  if (!context && !url) return true /* не Netlify — локальная разработка */
  if (context !== 'production') return false
  return (url ?? '').replace(/\/$/, '') === SITE_URL
}

/**
 * Боевой сайт на своём домене — и только он. В отличие от isIndexable,
 * локальный запуск сюда НЕ входит: здесь вопрос не «пускать ли
 * поисковик», а «можно ли показывать примеры вместо настоящих данных».
 * Локально и на тестовом адресе — можно, на боевом — нет.
 */
export function isLiveSite(): boolean {
  return process.env.CONTEXT === 'production' && (process.env.URL ?? '').replace(/\/$/, '') === SITE_URL
}
