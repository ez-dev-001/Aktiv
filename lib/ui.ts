/* ── Плюралізація ── */

/** 1 послуга, 2 послуги, 5 послуг. */
export function pluralUk(n: number, one: string, few: string, many: string) {
  const d = n % 10
  const dd = n % 100
  if (d === 1 && dd !== 11) return one
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return few
  return many
}

/** 1 service, 2 services. */
export const pluralEn = (n: number, one: string, other: string) => (n === 1 ? one : other)

/* ── Дати ── */

/** «8 жовтня 2026 р.» / «8 October 2026». */
export function formatDate(lang: string, iso?: string, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long', year: 'numeric' }) {
  if (!iso) return null
  const d = new Date(iso)
  return Number.isNaN(d.getTime()) ? null : d.toLocaleDateString(INTL_LOCALE[asLocale(lang)], opts)
}

/** Дата з часом: «8 жовтня о 14:05» / «8 October at 14:05». */
export function formatDateTime(lang: string, iso: string, opts: Intl.DateTimeFormatOptions) {
  return new Date(iso).toLocaleString(INTL_LOCALE[asLocale(lang)], opts)
}

